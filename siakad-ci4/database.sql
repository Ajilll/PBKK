-- Import lewat phpMyAdmin (tab Import) atau: mysql -u root < database.sql
CREATE DATABASE IF NOT EXISTS db_akademik CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE db_akademik;

SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS nilai, krs, kelas, mata_kuliah, mahasiswa, dosen, prodi, users;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(30) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  nama VARCHAR(100) NOT NULL,
  role ENUM('admin','dosen','mahasiswa') NOT NULL
) ENGINE=InnoDB;

CREATE TABLE prodi (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  kode VARCHAR(10) NOT NULL UNIQUE,
  nama VARCHAR(100) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE mahasiswa (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL UNIQUE,
  nim VARCHAR(20) NOT NULL UNIQUE,
  nama VARCHAR(100) NOT NULL,
  prodi_id INT UNSIGNED NOT NULL,
  angkatan SMALLINT UNSIGNED NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (prodi_id) REFERENCES prodi(id)
) ENGINE=InnoDB;

CREATE TABLE dosen (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id INT UNSIGNED NOT NULL UNIQUE,
  nidn VARCHAR(20) NOT NULL UNIQUE,
  nama VARCHAR(100) NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE mata_kuliah (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  kode VARCHAR(15) NOT NULL UNIQUE,
  nama VARCHAR(100) NOT NULL,
  sks TINYINT UNSIGNED NOT NULL
) ENGINE=InnoDB;

CREATE TABLE kelas (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  mata_kuliah_id INT UNSIGNED NOT NULL,
  dosen_id INT UNSIGNED NOT NULL,
  periode VARCHAR(20) NOT NULL,
  hari ENUM('Senin','Selasa','Rabu','Kamis','Jumat','Sabtu') NOT NULL,
  jam_mulai TIME NOT NULL,
  jam_selesai TIME NOT NULL,
  ruang VARCHAR(20) NOT NULL,
  kuota SMALLINT UNSIGNED NOT NULL,
  FOREIGN KEY (mata_kuliah_id) REFERENCES mata_kuliah(id),
  FOREIGN KEY (dosen_id) REFERENCES dosen(id)
) ENGINE=InnoDB;

CREATE TABLE krs (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  mahasiswa_id INT UNSIGNED NOT NULL,
  kelas_id INT UNSIGNED NOT NULL,
  dibuat_pada TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_krs (mahasiswa_id, kelas_id),
  FOREIGN KEY (mahasiswa_id) REFERENCES mahasiswa(id) ON DELETE CASCADE,
  FOREIGN KEY (kelas_id) REFERENCES kelas(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE nilai (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  krs_id INT UNSIGNED NOT NULL UNIQUE,
  angka DECIMAL(5,2) NOT NULL,
  huruf VARCHAR(2) NOT NULL,
  bobot DECIMAL(2,1) NOT NULL,
  FOREIGN KEY (krs_id) REFERENCES krs(id) ON DELETE CASCADE
) ENGINE=InnoDB;
